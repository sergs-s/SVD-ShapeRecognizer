package svd.recognizer.math;

import java.util.Arrays;

/**
 * Контейнер результата сингулярного разложения матрицы A = U · Σ · Vᵀ.
 *
 * Содержит три составляющие разложения:
 * 1. Сингулярные значения (диагональ Σ) в невозрастающем порядке — «энергия»
 *    матрицы по главным направлениям. Для бинарного изображения фигуры это
 *    компактная числовая подпись формы: σ-вектор.
 * 2. Матрицу левых сингулярных векторов U (ортонормированный базис в
 *    пространстве строк изображения).
 * 3. Матрицу правых сингулярных векторов V (ортонормированный базис в
 *    пространстве столбцов).
 *
 * На текущем этапе распознавание фигур использует только σ-вектор (первые
 * сингулярные значения). Матрицы U и V сохранены сознательно: при переходе к
 * задаче лиц (eigenfaces) именно сингулярные векторы образуют собственное
 * подпространство класса, в которое проецируется неизвестный образец. Хранение
 * полного результата позволяет сделать этот переход без изменения архитектуры.
 *
 * @author ssv
 */
public class SvdResult {

    /** Сингулярные значения σᵢ в невозрастающем порядке (σ₁ ≥ σ₂ ≥ … ≥ 0). */
    private final double[] singularValues;

    /** Левые сингулярные векторы (столбцы U). */
    private final double[][] u;

    /** Правые сингулярные векторы (столбцы V). */
    private final double[][] v;

    public SvdResult(double[] singularValues, double[][] u, double[][] v) {
        this.singularValues = singularValues;
        this.u = u;
        this.v = v;
    }

    /**
     * @return сингулярные значения в невозрастающем порядке
     */
    public double[] getSingularValues() {
        return singularValues;
    }

    /**
     * @return матрица левых сингулярных векторов U
     */
    public double[][] getU() {
        return u;
    }

    /**
     * @return матрица правых сингулярных векторов V
     */
    public double[][] getV() {
        return v;
    }

    /**
     * Численный ранг матрицы — количество сингулярных значений, превышающих
     * порог eps. Малые σ ниже eps считаются нулевыми (шум/округление).
     *
     * Геометрический смысл для фигур: чем «глаже» и регулярнее фигура (например,
     * идеальный квадрат из прямых линий), тем ниже её ранг — энергия
     * сосредоточена в нескольких первых σ; рукописная дрожащая линия даёт
     * высокий ранг (энергия размазана по многим σ).
     *
     * @param eps порог отсечения малых сингулярных значений
     * @return число значимых сингулярных значений
     */
    public int getRank(double eps) {
        int rank = 0;
        for (double s : singularValues) {
            if (s > eps) {
                rank++;
            }
        }
        return rank;
    }

    /**
     * Первые k сингулярных значений — усечённый σ-вектор, используемый как
     * признак формы. Берутся именно старшие σ, так как они несут основную
     * долю «энергии» формы, а хвост — мелкие детали и шум.
     *
     * @param k желаемое число значений (усекается до длины массива)
     * @return массив из первых min(k, length) сингулярных значений
     */
    public double[] getTopSingularValues(int k) {
        int n = Math.min(k, singularValues.length);
        return Arrays.copyOf(singularValues, n);
    }
}
